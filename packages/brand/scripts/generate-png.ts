/**
 * One-time script: rasterises sailboat.svg → sailboat.png at 64×64.
 * White-filled icon on a transparent background for email clients.
 *
 * Run:  bun run gen:png           (from packages/brand)
 * Output is committed at apps/dashboard/public/sailboat.png.
 */
import { Resvg } from "@resvg/resvg-js";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const dir = dirname(fileURLToPath(import.meta.url));
const root = resolve(dir, "../../..");

const SAILBOAT_PATH =
  "M247.21,172.53A8,8,0,0,0,240,168H144V144h72a8,8,0,0,0,5.92-13.38L144,44.91V8a8,8,0,0,0-14.21-5l-104,128A8,8,0,0,0,32,144h96v24H16a8,8,0,0,0-6.25,13l29.6,37a15.93,15.93,0,0,0,12.49,6H204.16a15.93,15.93,0,0,0,12.49-6l29.6-37A8,8,0,0,0,247.21,172.53ZM197.92,128H144V68.69ZM48.81,128,128,30.53V128Zm155.35,80H51.84l-19.2-24H223.36Z";

const svgSource = `<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256" viewBox="0 0 256 256">
  <path fill="#f3f1eb" d="${SAILBOAT_PATH}" />
</svg>`;

const size = 64;
const resvg = new Resvg(svgSource, {
  fitTo: { mode: "width", value: size },
});
const png = resvg.render().asPng();

const outPath = resolve(root, "apps/dashboard/public/sailboat.png");
writeFileSync(outPath, png);

// Write base64 constant so the email package can embed the logo inline.
const base64 = Buffer.from(png).toString("base64");
const tsOut = resolve(dir, "../src/sailboat-png.ts");
writeFileSync(
  tsOut,
  `// Auto-generated by packages/brand/scripts/generate-png.ts — do not edit manually.\n// Re-generate: bun run gen:png (from packages/brand)\nexport const SAILBOAT_PNG_BASE64 = "${base64}";\n`,
);

const bytes = png.byteLength;
console.log(`Generated ${outPath} (${bytes} bytes, ${size}×${size})`);
console.log(`Updated ${tsOut}`);
